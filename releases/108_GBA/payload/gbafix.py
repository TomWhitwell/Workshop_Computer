#!/usr/bin/env python3
"""gbafix.py — insert the Nintendo logo + fix the GBA header checksum, in place.

A dependency-free reimplementation of the parts of devkitPro's `gbafix` that a multiboot
image needs: the GBA BIOS compares the 156-byte Nintendo logo (0x04..0x9F) against its own
copy and validates the header complement byte (0xBD), locking up if either is wrong.

This writes:
  - the correct Nintendo logo at 0x04..0x9F,
  - the fixed byte 0x96 at 0xB2,
  - the header complement at 0xBD, computed as -(0x19 + sum(bytes[0xA0..0xBD))) & 0xFF.

It does NOT touch the title/game-code/etc. (crt0.s already sets those). Padding to a
16-byte multiple is done by bin2h.py.

Usage: gbafix.py <rom.mb>

Logo bytes are the public, fixed values embedded in every GBA ROM header (taken verbatim
from devkitPro/gba-tools gbafix.c `good_header`).
"""
import sys

NINTENDO_LOGO = bytes([
    0x24,0xFF,0xAE,0x51,0x69,0x9A,0xA2,0x21,0x3D,0x84,0x82,0x0A,0x84,0xE4,0x09,0xAD,
    0x11,0x24,0x8B,0x98,0xC0,0x81,0x7F,0x21,0xA3,0x52,0xBE,0x19,0x93,0x09,0xCE,0x20,
    0x10,0x46,0x4A,0x4A,0xF8,0x27,0x31,0xEC,0x58,0xC7,0xE8,0x33,0x82,0xE3,0xCE,0xBF,
    0x85,0xF4,0xDF,0x94,0xCE,0x4B,0x09,0xC1,0x94,0x56,0x8A,0xC0,0x13,0x72,0xA7,0xFC,
    0x9F,0x84,0x4D,0x73,0xA3,0xCA,0x9A,0x61,0x58,0x97,0xA3,0x27,0xFC,0x03,0x98,0x76,
    0x23,0x1D,0xC7,0x61,0x03,0x04,0xAE,0x56,0xBF,0x38,0x84,0x00,0x40,0xA7,0x0E,0xFD,
    0xFF,0x52,0xFE,0x03,0x6F,0x95,0x30,0xF1,0x97,0xFB,0xC0,0x85,0x60,0xD6,0x80,0x25,
    0xA9,0x63,0xBE,0x03,0x01,0x4E,0x38,0xE2,0xF9,0xA2,0x34,0xFF,0xBB,0x3E,0x03,0x44,
    0x78,0x00,0x90,0xCB,0x88,0x11,0x3A,0x94,0x65,0xC0,0x7C,0x63,0x87,0xF0,0x3C,0xAF,
    0xD6,0x25,0xE4,0x8B,0x38,0x0A,0xAC,0x72,0x21,0xD4,0xF8,0x07,
])
assert len(NINTENDO_LOGO) == 0xA0 - 0x04


def fix(path):
    with open(path, "rb") as f:
        d = bytearray(f.read())
    if len(d) < 0xC0:
        sys.exit(f"error: {path} is smaller than a GBA header (0xC0 bytes)")

    # logo (0x04..0x9F)
    d[0x04:0xA0] = NINTENDO_LOGO
    # fixed byte
    d[0xB2] = 0x96
    # header complement (0xBD): -(0x19 + sum(0xA0..0xBD)) & 0xFF
    d[0xBD] = 0  # exclude from the sum
    c = sum(d[0xA0:0xBD]) & 0xFF
    d[0xBD] = (-(0x19 + c)) & 0xFF

    with open(path, "wb") as f:
        f.write(d)
    print(f"gbafix.py: patched logo + complement (0x{d[0xBD]:02x}) in {path}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: gbafix.py <rom.mb>")
    fix(sys.argv[1])
