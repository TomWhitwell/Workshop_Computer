"""Generate measured +/-40 degree, 64-tap minimum-phase experimental banks.

The archive's actual integer azimuth labels are used to resample each sparse
elevation ring onto the existing 72-direction grid. Magnitudes interpolate
offline before minimum-phase reconstruction; no extra convolution at runtime.
"""
import hashlib, io, json, pathlib, re, wave, zipfile
import numpy as np
from scipy.signal import resample_poly
HERE=pathlib.Path(__file__).resolve().parents[1]
ROOT=HERE
ARCHIVE=ROOT/'vendor/KEMAR/diffuse.zip'
SCALE=0.48727477260326996
TAPS=64
z=zipfile.ZipFile(ARCHIVE)
bank=[]
report={'archive_sha256':hashlib.sha256(ARCHIVE.read_bytes()).hexdigest(),
        'elevations_degrees':[-40,40], 'rate':48000, 'taps':TAPS,
        'azimuth_directions':72,'global_scale':SCALE,'rings':{}}
for elevation in (-40,40):
    entries=sorted((int(re.search(r'e(\d+)a.wav$',n)[1]),n) for n in z.namelist()
                   if n.startswith(f'elev{elevation}/') and n.endswith('.wav'))
    azimuth=np.array([a for a,n in entries]);assert azimuth[0]==0 and azimuth[-1]==180
    magnitudes=[]
    for a,n in entries:
        with wave.open(io.BytesIO(z.read(n))) as w:
            assert (w.getframerate(),w.getnchannels(),w.getsampwidth())==(44100,2,2)
            h=np.frombuffer(w.readframes(w.getnframes()),dtype='<i2').reshape(-1,2)/32768.
        h=resample_poly(h,160,147,axis=0)
        magnitudes.append(np.maximum(np.abs(np.fft.rfft(h,2048,axis=0)),1e-5))
    ring=[];errors={32:[],64:[]};energy={32:[],64:[]}
    frequency=np.fft.rfftfreq(2048,1/48000);band=(frequency>=1000)&(frequency<=12000)
    for degree in range(0,360,5):
        az=degree if degree<=180 else 360-degree
        high=min(int(np.searchsorted(azimuth,az,side='right')),len(entries)-1)
        low=max(0,high-1);frac=(az-azimuth[low])/(azimuth[high]-azimuth[low])
        magnitude=magnitudes[low]*(1-frac)+magnitudes[high]*frac
        if degree>180:magnitude=magnitude[:,::-1]
        cep=np.fft.irfft(np.log(magnitude),2048,axis=0)
        lift=np.zeros_like(cep);lift[0]=cep[0];lift[1:1024]=2*cep[1:1024];lift[1024]=cep[1024]
        minimum=np.fft.irfft(np.exp(np.fft.rfft(lift,axis=0)),2048,axis=0)
        for taps in (32,64):
            candidate=minimum[:taps].T.copy();candidate[:,-8:]*=np.cos(np.linspace(0,np.pi/2,8))**2
            candidate=np.rint(candidate*SCALE*16384)/16384
            got=np.maximum(np.abs(np.fft.rfft(candidate,2048,axis=1)),1e-5)
            error=20*np.log10(got/(magnitude.T*SCALE))
            errors[taps].extend(error[:,band].ravel())
            energy[taps].extend(np.sum(minimum[:taps]**2,axis=0)/np.sum(minimum**2,axis=0))
        raw=minimum[:TAPS].T.copy();raw[:,-8:]*=np.cos(np.linspace(0,np.pi/2,8))**2
        ring.append(np.rint(raw*SCALE*16384).astype(np.int32))
    bank.append(ring)
    report['rings'][str(elevation)]={'measured_azimuths':azimuth.tolist(),
        'max_direction_ear_l1_q14':int(np.abs(ring).sum(axis=2).max()),
        'comparison':{str(t):{'magnitude_error_1k_12k_rms_db':float(np.sqrt(np.mean(np.array(errors[t])**2))),
            'min_energy_retained_before_taper':float(min(energy[t]))} for t in (32,64)}}
q=np.array(bank);assert np.abs(q).max()<=32767
# Include unchanged horizontal bank and neutral impulse in the partial-update
# bound: slewed coefficients can contain taps from several profile targets.
text=(HERE/'src/dsp/hrtf_table_64.h').read_text().split('= {',1)[1]
horizontal=np.array(list(map(int,re.findall(r'-?\d+',text)))).reshape(72,2,TAPS)
maxima=np.maximum(np.abs(q).max(axis=(0,1)),np.abs(horizontal).max(axis=0))+2
maxima[:,0]=np.maximum(maxima[:,0],16384)
bound=int(maxima.sum(axis=1).max())
assert bound*4096<2**31 and (bound*4096>>14)<32768
report['worst_combined_mixture_l1_q14']=bound
lines=['// Generated by tools/generate_elevation.py.',
       '// Measurements (c) 1994 MIT Media Laboratory: Bill Gardner and Keith Martin.',
       '// Data terms: vendor/KEMAR/SOURCE_TERMS.md in the repository root.',
       '// Generator (c) 2026 Adrian Vos (soveda), MIT. Data retains its own terms.',
       '#pragma once','#include <cstdint>','namespace spatial {',
       f'constexpr int kElevationMixtureL1Bound={bound};',
       f'alignas(4) constexpr int16_t kElevationHrtf[2][72][2][{TAPS}]={{']
for ring in q:
    lines.append('{')
    for direction in ring:lines.append('{'+','.join('{'+','.join(map(str,ear))+'}' for ear in direction)+'},')
    lines.append('},')
lines+=['};','}']
(HERE/'src/dsp/elevation_table.h').write_text('\n'.join(lines)+'\n')
(HERE/'vendor/KEMAR/elevation_generation.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
