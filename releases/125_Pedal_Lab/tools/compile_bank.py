#!/usr/bin/env python3
"""Assemble SpinASM and compile constant instructions into straight-line C++."""
import argparse, importlib.util, json, pathlib, struct, hashlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('assembler',ROOT/'vendor/assembler/assembler.py')
asm=importlib.util.module_from_spec(spec); spec.loader.exec_module(asm)

def assemble(path):
    p=asm.fv1parse(path.read_text(encoding='utf-8-sig'),spinreals=True,clamp=False,
                   wfunc=lambda *a:None,efunc=lambda x:print(x))
    p.parse()
    # MEM reserves the inclusive end address as well as the requested span.
    # Reject any allocation extending beyond the final physical word.
    if p.delaymem > 32768:
        raise ValueError(f'{path}: delay allocation exceeds 32768 words')
    words=list(struct.unpack('>128I',p.program))
    # Reject reserved opcodes/CHO variants rather than silently emit NOPs.
    for pc,w in enumerate(words):
        op=w&31
        if op>20 or (op==20 and (w>>30)==1):
            raise ValueError(f'{path}:{pc}: unsupported instruction {w:08x}')
    return words

def generate(paths,out,limit=6):
    if not 1<=len(paths)<=limit: raise ValueError(f'Choose 1 to {limit} programs')
    out.mkdir(parents=True,exist_ok=True)
    credits={}
    if (ROOT/'algorithms/catalogue.json').exists():
        credits={str((ROOT/e['path']).resolve()):e for e in json.loads((ROOT/'algorithms/catalogue.json').read_text())['programs']}
    titles=[]
    lines=['// Generated by tools/compile_bank.py; algorithms retain upstream licences. See bank.json.',
           '#pragma once','#include "machine.hpp"','namespace spin {']
    manifest=[]
    for n,path in enumerate(paths):
        words=assemble(path); used=128
        while used and words[used-1]==0x11:used-=1
        targets={min(128,i+1+((w>>21)&63)) for i,w in enumerate(words[:used]) if w&31==17}
        lines += [f'inline void program_{n}(Machine &s) {{']
        for i,w in enumerate(words[:used]):
            if i in targets:lines += [f'L{i}:;']
            if w&31==17:
                mask=(w>>27)&31; target=min(128,i+1+((w>>21)&63))
                conditions=[]
                if mask==0:conditions=['true']
                for bit,expr in [(1,'s.acc<0'),(2,'s.acc>=0'),(4,'s.acc==0'),(8,'((s.acc<0)!=(s.pacc<0))'),(16,'!s.first_run')]:
                    if mask&bit:conditions.append(expr)
                lines += [f'if ({" || ".join(conditions)}) goto L{target};']
            else:
                lines += [f'{{ uint32_t pc=0; bool skip=false; constexpr auto d=decode(0x{w:08x}u); s.execute_instruction(d,pc,skip); }}']
        for target in sorted(t for t in targets if t>=used):lines += [f'L{target}:;']
        lines += ['}']
        (out/f'program_{n}.bin').write_bytes(struct.pack('>128I',*words))
        manifest.append({'slot':n,'name':path.stem,'source':str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path),'instructions':used,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
        credit=credits.get(str(path.resolve()))
        if credit:
            manifest[-1].update({key:credit[key] for key in ['id','author','description','controls','license','source_url','upstream_commit']})
            manifest[-1]['title']=credit['name']
            manifest[-1]['validation']=credit.get('validation',{'status':'not run'})
        titles.append(credit['name'] if credit else path.stem)
    lines += [f'inline constexpr unsigned program_count={len(paths)};',
              'inline constexpr Program programs[] = {'+','.join(f'program_{n}' for n in range(len(paths)))+'};',
              'inline constexpr const char *program_names[] = {'+','.join(json.dumps(title) for title in titles)+'};','}']
    (out/'bank.hpp').write_text('\n'.join(lines)+'\n')
    (out/'bank.json').write_text(json.dumps(manifest,indent=2)+'\n')
    return manifest

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('programs',type=pathlib.Path,nargs='+');p.add_argument('-o','--output',type=pathlib.Path,default=ROOT/'generated')
    a=p.parse_args()
    try:
        for row in generate([p.resolve() for p in a.programs],a.output):print(f'{row["slot"]+1}: {row["name"]} ({row["instructions"]} instructions)')
    except (ValueError,OSError) as e:p.error(str(e))
if __name__=='__main__':main()
